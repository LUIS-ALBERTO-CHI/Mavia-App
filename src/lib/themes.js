const ACCENT_KEYS = ["--primary","--on-primary","--surface-tint","--gradient-primary","--gradient-lime","--lime","--on-lime"];
const ALL_KEYS = [...new Set(THEMES.flatMap(t => Object.keys(t.tokens)))];

export function getSavedTheme() {
  try { return localStorage.getItem("mavia_theme") || "mentry"; } catch { return "mentry"; }
}

export function applyTheme(id) {
  const t = THEMES.find(x => x.id === id) || THEMES[0];
  if (typeof document === "undefined") return t.id;
  const roots = [document.documentElement, document.body];
  const appRoot = document.querySelector(".app-root");
  if (appRoot) roots.push(appRoot);
  const dark = document.documentElement.classList.contains("dark");
  roots.forEach(r => ALL_KEYS.forEach(k => r.style.removeProperty(k)));
  Object.entries(t.tokens).forEach(([k, v]) => {
    if (dark && !ACCENT_KEYS.includes(k)) return;
    roots.forEach(r => r.style.setProperty(k, v));
  });
  try { localStorage.setItem("mavia_theme", t.id); } catch {}
  return t.id;
}
